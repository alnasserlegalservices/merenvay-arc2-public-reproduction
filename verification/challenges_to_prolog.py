#!/usr/bin/env python3
"""Convert ARC challenge JSON into Prolog facts without test outputs.

The generated module contains only:
  arc_input_task(TaskId, TrainingPairs, TestInputs).

TrainingPairs include demonstration outputs because ARC solvers are allowed to
see them. Test outputs are intentionally never serialized into the generated
file, even if the input source happens to contain them.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def prolog_list(obj: Any) -> str:
    if isinstance(obj, list):
        return "[" + ",".join(prolog_list(x) for x in obj) + "]"
    if isinstance(obj, bool) or not isinstance(obj, int):
        raise TypeError(f"ARC grids must contain integers, got {type(obj).__name__}")
    if not 0 <= obj <= 9:
        raise ValueError(f"ARC cell out of range 0..9: {obj}")
    return str(obj)


def prolog_atom(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def load_tasks(source: Path) -> dict[str, dict[str, Any]]:
    if source.is_dir():
        tasks: dict[str, dict[str, Any]] = {}
        for path in sorted(source.glob("*.json")):
            tasks[path.stem] = json.loads(path.read_text(encoding="utf-8"))
        return tasks

    data = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Challenge JSON must be an object keyed by task id")
    return data


def validate_grid(grid: Any) -> None:
    if not isinstance(grid, list) or not grid or not all(isinstance(r, list) and r for r in grid):
        raise ValueError("Grid must be a non-empty rectangular list of rows")
    width = len(grid[0])
    if any(len(row) != width for row in grid):
        raise ValueError("Grid rows must be rectangular")
    if len(grid) > 30 or width > 30:
        raise ValueError("ARC grid dimensions must not exceed 30x30")
    for row in grid:
        for cell in row:
            if isinstance(cell, bool) or not isinstance(cell, int) or not 0 <= cell <= 9:
                raise ValueError(f"Invalid ARC cell: {cell!r}")


def convert(source: Path, dest: Path) -> None:
    tasks = load_tasks(source)
    lines = [
        "% Auto-generated by verification/challenges_to_prolog.py",
        "% Test outputs are intentionally absent.",
        ":- module(arc_input_tasks, [arc_input_task/3]).",
        ":- discontiguous arc_input_task/3.",
        "",
    ]

    for task_id, task in sorted(tasks.items()):
        train = task.get("train")
        tests = task.get("test")
        if not isinstance(train, list) or not train:
            raise ValueError(f"{task_id}: missing training pairs")
        if not isinstance(tests, list) or not tests:
            raise ValueError(f"{task_id}: missing test inputs")

        pairs = []
        for pair in train:
            inp = pair.get("input")
            out = pair.get("output")
            validate_grid(inp)
            validate_grid(out)
            pairs.append(f"pair({prolog_list(inp)},{prolog_list(out)})")

        test_inputs = []
        for test in tests:
            inp = test.get("input")
            validate_grid(inp)
            test_inputs.append(prolog_list(inp))

        lines.append(
            f"arc_input_task({prolog_atom(task_id)},"
            f"[{','.join(pairs)}],"
            f"[{','.join(test_inputs)}])."
        )

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(tasks)} answer-isolated tasks to {dest}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path, help="ARC challenge JSON file or directory")
    parser.add_argument("dest", type=Path, help="Output Prolog fact file")
    args = parser.parse_args()
    convert(args.source, args.dest)


if __name__ == "__main__":
    main()
